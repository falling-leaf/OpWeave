#!/usr/bin/env python3
"""
Hermes-generated year_predict inference script (execution phase only).

This script was generated by Hermes agent. It is used in scheduling tests
to measure EXECUTION latency under CPU load, with generation cost fixed.

Outputs a JSON line to stdout: {"inference_ms": ..., "rows": ...}
"""
import torch
import pandas as pd
import time
import json
import sys

MODEL_PATH = "/home/why/baseline/models/year_predict.pt"
DATA_PATH = "/home/why/baseline/data/series/yead_predict/YearPredictionMSD.csv"

row_count = int(sys.argv[1]) if len(sys.argv) > 1 else 10000

# Load model (not timed — represents post-generation state where model is available)
model = torch.jit.load(MODEL_PATH, map_location="cpu")
model.eval()

# Load data (timed — part of execution)
t0 = time.perf_counter()

df = pd.read_csv(DATA_PATH, nrows=row_count)
df = df.drop(columns=["value90"])
features = df.values.astype("float32")
X = torch.from_numpy(features)

batch_size = 32
n = X.shape[0]
num_batches = (n + batch_size - 1) // batch_size

# Warmup batch
with torch.no_grad():
    _ = model(X[:batch_size])

# Timed inference
start = time.perf_counter()
with torch.no_grad():
    for i in range(num_batches):
        batch = X[i * batch_size : (i + 1) * batch_size]
        _ = model(batch)
end = time.perf_counter()

inference_ms = (end - start) * 1000
total_ms = (end - t0) * 1000

print(json.dumps({"inference_ms": round(inference_ms, 2), "total_ms": round(total_ms, 2), "rows": n}))
